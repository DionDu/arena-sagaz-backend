# A máscara de 64 bits. Em Dart e em Rust o inteiro **é** de 64 bits e o excesso
# se perde sozinho; em Python os inteiros são de tamanho ilimitado, então cada
# XOR precisa ser recortado à mão para o padrão de bits continuar o mesmo.
