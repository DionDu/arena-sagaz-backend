"""Os números do hash de Zobrist — **copiados** do motor que roda no aparelho.

Por que copiados, e não sorteados aqui
--------------------------------------
O hash de Zobrist é o XOR de um número aleatório por combinação (casa, peça).
Qual número não importa — desde que seja **o mesmo** nos três motores. E não é
possível sortear os mesmos em três linguagens: os geradores pseudoaleatórios de
Dart, Rust e Python produzem sequências diferentes a partir da mesma semente.

Então a tabela nasce em um lugar só — `Random(20260724)` do Dart, dentro de
`motor_dart/lib/tabuleiro_damas.dart` — e os outros dois **importam**. O Rust já
fazia isso desde 21/08/2026 (`motor_rust/src/zobrist.rs`, gerado por
`motor_dart/bin/dump_zobrist.dart`); este arquivo fecha o triângulo em
03/09/2026.

⚠️ **Por que isto tinha de existir.** Enquanto o Python usava a posição inteira
como chave da tabela de transposição e o app usava Zobrist, os dois **podavam
árvores diferentes**: medido em 03/09/2026, a mesma busca de profundidade 10
custava 98.583 nós no Python e 98.938 no Dart. Os lances escolhidos batiam
naquelas posições, mas nada garantia que batessem com **teto de nós** — e teto é
exatamente como os quatro níveis do app são definidos. Um motor de referência que
poda diferente do motor em campo mede um aparelho que ninguém tem.

⚠️ **Não edite os números à mão.** Eles vêm do Dart; o cadeado
`testes/test_zobrist_damas.py` compara este arquivo com `zobrist.rs` e falha se
divergirem. Para regerar: rode `dart run bin/dump_zobrist.dart` (que reescreve o
`.rs`) e depois converta para cá.

Os índices
----------
`ZOBRIST_PECA[casa][peca]` — `casa` de 0 a 32 (a 0 nunca é usada; existe para o
índice ser o número da casa, sem "menos um"), e `peca` é o valor de `Peca`:
0 vazia · 1 pedra branca · 2 dama branca · 3 pedra preta · 4 dama preta. É a
mesma ordem nos três motores.

Os valores são **inteiros sem sinal de 64 bits**. O Dart guarda os mesmos bits
como inteiro com sinal (lá não existe `int` sem sinal), e isso não muda nada:
o índice na tabela é `hash & máscara`, que lê só os bits baixos, e a comparação
de chave é entre valores do mesmo lado. O padrão de bits é idêntico.
"""
